import type { UiContext, UiNode, UiTreeItem, ViewLine, ViewSegment } from "@amira/api"
import { chrome, repeatCells } from "./chrome.ts"
import { formatCost } from "./format.ts"
import {
  type DashboardAgent,
  type DashboardFile,
  type DashboardPhase,
  type DashboardSource,
  rowCount,
  rowLabel,
} from "./source.ts"
import { dashboardStatus, displayState, statusBadge, statusMark, statusTone } from "./status.ts"

const part = (text: string, kind: ViewSegment["kind"] = "text"): ViewSegment => ({ text, kind })
const segments = (parts: ViewSegment[]): ViewLine => ({ kind: "segments", parts })
const text = (lines: ViewLine[], id?: string): UiNode => ({ type: "text", id, lines })
export const clock = (at?: number) =>
  at === undefined ? "--:--:--" : new Date(at).toISOString().slice(11, 19)
export const duration = (ms?: number, opts: Pick<UiContext, "glyphs"> = {}) =>
  ms === undefined ? chrome(opts)`—` : `${Math.max(0, Math.round(ms / 1000))}s`
/** Cell-aware fields, including CJK/emoji. No ANSI styling is generated by the extension. */
function field(value: string, width: number, opts: Pick<UiContext, "glyphs"> = {}): string {
  // biome-ignore lint/suspicious/noControlCharactersInRegex: sanitize source text before cell measurement
  const clean = value.replace(/[\x00-\x1f\x7f-\x9f]/g, " ")
  if (Bun.stringWidth(clean) <= width) return clean + " ".repeat(width - Bun.stringWidth(clean))
  const marker = opts.glyphs?.more ?? "…"
  const more = Bun.stringWidth(marker) <= width ? marker : ""
  const available = width - Bun.stringWidth(more)
  let result = ""
  for (const { segment } of new Intl.Segmenter().segment(clean)) {
    if (Bun.stringWidth(result + segment) > available) break
    result += segment
  }
  return `${result}${more}${" ".repeat(Math.max(0, available - Bun.stringWidth(result)))}`
}

export function phaseInfo(phase: DashboardPhase, now: number, opts: Pick<UiContext, "glyphs"> = {}) {
  const c = chrome(opts)
  const agents = phase.groups.flatMap((group) => group.agents)
  const statuses = phase.groups.flatMap((group) =>
    group.status ? [dashboardStatus({ ...group, status: group.status })] : group.agents.map(dashboardStatus),
  )
  const group = phase.groups.length === 1 ? phase.groups[0] : undefined
  const status =
    (phase.status ? dashboardStatus({ ...phase, status: phase.status }) : undefined) ??
    (group?.status ? dashboardStatus({ ...group, status: group.status }) : undefined) ??
    (["running", "failed", "paused", "queued", "idle", "stopped"] as const).find((status) =>
      statuses.includes(status),
    ) ??
    (statuses.length ? "done" : "queued")
  const starts = [...agents, ...phase.groups].flatMap((item) =>
    item.startedAt === undefined ? [] : [item.startedAt],
  )
  const startedAt = phase.startedAt ?? (starts.length ? Math.min(...starts) : undefined)
  const ends = agents.flatMap((agent) =>
    agent.startedAt === undefined || agent.durationMs === undefined
      ? []
      : [agent.startedAt + agent.durationMs],
  )
  const durationMs =
    phase.durationMs ??
    group?.durationMs ??
    (startedAt === undefined
      ? undefined
      : status === "running" || status === "paused"
        ? now - startedAt
        : ends.length === agents.length && ends.length
          ? Math.max(...ends) - startedAt
          : undefined)
  const steps =
    phase.stepCount ??
    (phase.groups.every((group) => group.stepCount !== undefined) && phase.groups.length
      ? phase.groups.reduce((sum, group) => sum + group.stepCount!, 0)
      : undefined)
  const stageOnly = agents.length > 0 && agents.every((agent) => agent.card?.kind === "stage")
  const description =
    phase.description ??
    group?.description ??
    (stageOnly
      ? rowCount(agents)
      : status === "done"
        ? [
            ...(steps === undefined ? [] : [`${steps} steps`]),
            rowCount(agents),
            ...(durationMs === undefined ? [] : [duration(durationMs, opts)]),
          ].join(c` · `)
        : status === "queued"
          ? "queued"
          : (agents.find((agent) => dashboardStatus(agent) === status)?.task ?? status))
  return {
    agents,
    status,
    startedAt,
    durationMs,
    description,
    stageOnly,
    ref: stageOnly ? undefined : (phase.ref ?? group?.ref ?? phase.id),
  }
}

function fileParts(file: DashboardFile, width: number, ctx: UiContext): ViewSegment[] {
  const counts = [
    file.added === undefined ? "" : `+${file.added}`,
    file.removed === undefined ? "" : `-${file.removed}`,
  ]
    .filter(Boolean)
    .join("  ")
  return [
    part(field(file.path, Math.max(1, width - (counts ? counts.length + 3 : 0)), ctx)),
    ...(counts ? [part(`   ${counts}`, "success")] : []),
  ]
}

/** Stage rollups are display text, never an agent's own usage. */
function stageHeading(agent: DashboardAgent, ctx: UiContext): ViewSegment[] {
  const c = chrome(ctx)
  const cost = agent.card?.costText ?? (agent.cost === undefined ? undefined : formatCost(agent.cost))
  return [
    ...statusMark(agent, ctx),
    part(` ${rowLabel(agent)}`, "accent"),
    part(c` · ${agent.card?.outcome || displayState(agent)}`, statusTone(agent)),
    ...(cost ? [part(c` · ${cost}`, "muted")] : []),
  ]
}

function stageDetail(agent: DashboardAgent): string {
  return agent.card?.detail ?? agent.task
}

/** A shared frame composed from selectable card heads and display-only semantic bodies. */
export function timeline(source: DashboardSource, ctx: UiContext, selected?: string): UiNode {
  const c = chrome(ctx)
  const snapshot = source.snapshot()
  const phases = snapshot.phases
  if (!phases.length)
    return text(
      [
        ...(snapshot.warning ? [{ kind: "warning" as const, text: snapshot.warning }] : []),
        {
          kind: "text" as const,
          text: snapshot.note ?? "No agents yet. Close this view and ask Amira to delegate a task.",
        },
      ],
      "empty",
    )
  const narrow = ctx.width < 110
  const selectedPhase =
    phases.find(
      (phase) =>
        `phase:${phase.id}` === ctx.state.selected.timeline ||
        phase.groups.some((group) => group.agents.some((agent) => agent.id === selected)),
    ) ??
    phases.find((phase) => phaseInfo(phase, ctx.now, ctx).status === "running") ??
    phases[0]
  const expanded = ctx.state.expanded.timeline
  const open = (key: string) => expanded === undefined || expanded.includes(key)
  // The host shares the widest lead across the tree. Stage-only history needs no unknown clock slot.
  const compactLead = phases.every((phase) => {
    const info = phaseInfo(phase, ctx.now, ctx)
    return info.stageOnly && info.startedAt === undefined
  })
  const innerWidth = Math.max(1, ctx.width - (compactLead ? 10 : 22))
  const frame = (left: string, right: string): UiNode =>
    text([segments([part(` ${left}${repeatCells(c`─`, innerWidth + 2)}${right}`, "muted")])])
  const bodyLine = (node: UiNode): UiNode => ({
    type: "row",
    children: [
      { size: 3, node: text([segments([part(c` │ `, "muted")])]) },
      { node },
      { size: 3, node: text([segments([part(c` │ `, "muted")])]) },
    ],
  })
  const items: UiTreeItem[] = []
  for (const [phaseIndex, phase] of phases.entries()) {
    const info = phaseInfo(phase, ctx.now, ctx)
    if (
      info.startedAt !== undefined &&
      phase.durationMs === undefined &&
      !(phase.groups.length === 1 && phase.groups[0]?.durationMs !== undefined) &&
      info.status === "running"
    )
      ctx.requestRefresh?.(1000)
    const key = `phase:${phase.id}`
    const showCards = open(key) && info.agents.length > 0 && (!narrow || phase === selectedPhase)
    const name = `${phase.name}${info.agents.length > 1 && !phase.name.includes("×") ? c` ×${info.agents.length}` : ""}`
    items.push({
      key,
      ...(compactLead
        ? {}
        : {
            lead: [
              part(
                info.stageOnly && info.startedAt === undefined ? "          " : `${clock(info.startedAt)}  `,
                "muted",
              ),
              ...statusMark(info, ctx),
            ],
          }),
      node: statusMark(info, ctx),
      row: [
        part(
          info.stageOnly ? `${name}  ` : `${field(name, narrow ? 14 : 15, ctx)} `,
          info.status === "running" ? "accent" : "text",
        ),
        part(info.description, "muted"),
        ...(info.stageOnly
          ? [
              part(c` · ${displayState(info)}`, statusTone(info)),
              ...(info.durationMs === undefined
                ? []
                : [part(c` · ${duration(info.durationMs, ctx)}`, "muted")]),
            ]
          : info.status === "running"
            ? [
                part(c`   ▏`),
                ...statusBadge(info, ctx),
                part(c` ${duration(info.durationMs, ctx)}▕`, "accent"),
              ]
            : []),
      ],
      aside: [part(`${narrow || !info.ref ? "" : `${info.ref}  `}${showCards ? c`▾` : c`▸`}`, "muted")],
      rail: true,
      expandable: info.agents.length > 0,
      underline: !showCards,
      ...(showCards ? { detail: frame(c`╭`, c`╮`) } : {}),
    })
    if (!showCards) continue
    for (const [index, agent] of info.agents.entries()) {
      const last = index === info.agents.length - 1
      const foldedFooter = last && !open(`agent:${agent.id}`)
      const stage = agent.card?.kind === "stage"
      const count = c`${rowCount(info.agents)} · ${info.agents.filter((agent) => displayState(agent) === "working").length} running`
      if (stage) {
        const detail = stageDetail(agent)
        const children: { size: number; node: UiNode }[] = []
        if (detail) children.push({ size: 1, node: bodyLine(text([{ kind: "muted", text: `  ${detail}` }])) })
        if (last) {
          children.push({
            size: 1,
            node: bodyLine(text([{ kind: "muted", text: c`${count} · e expand all · Read-only stage` }])),
          })
          children.push({ size: 1, node: frame(c`╰`, c`╯`) })
        } else children.push({ size: 1, node: bodyLine({ type: "rule" }) })
        items.push({
          key: `agent:${agent.id}`,
          node: [part(last && phaseIndex === phases.length - 1 ? c`└─` : c`├─`, "muted")],
          row: [part(foldedFooter ? c`─╰ ` : c`─▶ `, "muted"), ...stageHeading(agent, ctx)],
          // Host sides() prioritizes aside; never put stage content there at the expense of its label.
          aside: [part(foldedFooter ? c` ╯ ` : c` │ `, "muted")],
          rail: true,
          detail: { type: "column", children },
          underline: last,
        })
        continue
      }
      const detail = source.details(agent.id)
      const progress =
        agent.progress === undefined || !Number.isFinite(agent.progress)
          ? undefined
          : Math.max(0, Math.min(1, agent.progress))
      const filled = Math.round((progress ?? 0) * (narrow ? 6 : 14))
      const bar = repeatCells(c`━`, filled) + repeatCells(c`─`, (narrow ? 6 : 14) - filled)
      const can = (action: DashboardAgent["actions"][number]) =>
        !!source.act && agent.actions.includes(action)
      const labels = [
        part("Open diff", "accent"),
        ...(can("pause") || can("resume") ? [part(can("resume") ? "Resume" : "Pause")] : []),
        ...(can("request-changes") ? [part("Request changes")] : []),
        part(c`⋮`, "muted"),
      ]
      const actions = labels.flatMap((label, index) => (index ? [part("   "), label] : [label]))
      const changed = c`${agent.files.length} ${agent.files.length === 1 ? "file" : "files"} changed ▸`
      const children: { size?: number; node: UiNode }[] = [
        {
          size: 1,
          node: bodyLine(
            text([
              segments([
                part(
                  `  ${detail?.summary.map((line) => (line.kind === "segments" ? line.parts.map((part) => part.text).join("") : line.text)).join(" ") || agent.task}`,
                  "muted",
                ),
              ]),
            ]),
          ),
        },
      ]
      if (displayState(agent) === "done" && agent.durationMs !== undefined && !narrow)
        children.push({
          size: 1,
          node: bodyLine(text([segments([part(`  done in ${duration(agent.durationMs)}`, "muted")])])),
        })
      if (agent.files.length) {
        if (!narrow) children.push({ size: 1, node: bodyLine(text([])) })
        children.push({ size: 1, node: bodyLine(text([segments([part("  Changed files", "muted")])])) })
        for (const file of agent.files.slice(0, narrow ? 1 : 3))
          children.push({
            size: 1,
            node: bodyLine(
              text([segments([part("  "), ...fileParts(file, Math.min(52, innerWidth - 2), ctx)])]),
            ),
          })
        if (agent.files.length > (narrow ? 1 : 3))
          children.push({
            size: 1,
            node: bodyLine(
              text([
                segments([part(c`  +${agent.files.length - (narrow ? 1 : 3)} more · o open diff`, "muted")]),
              ]),
            ),
          })
      }
      if (last) {
        if (!narrow) children.push({ size: 1, node: bodyLine(text([])) })
        children.push({
          size: 1,
          node: bodyLine({
            type: "bar",
            left: [part(count, "muted")],
            right: narrow
              ? []
              : [part(c`e expand all · o diff · p pause/resume · r changes · a actions`, "muted")],
          }),
        })
        children.push({ size: 1, node: frame(c`╰`, c`╯`) })
      } else children.push({ size: 1, node: bodyLine({ type: "rule" }) })
      items.push({
        key: `agent:${agent.id}`,
        node: [part(last && phaseIndex === phases.length - 1 ? c`└─` : c`├─`, "muted")],
        row: [
          part(foldedFooter ? c`─╰ ` : c`─▶ `, "muted"),
          ...statusBadge(agent, ctx),
          part(" "),
          part(field(rowLabel(agent), narrow ? 10 : 12, ctx), "accent"),
          ...(!narrow
            ? [
                part(`  ${field(agent.task, 22, ctx)}  `),
                ...(agent.language
                  ? [
                      { kind: "chip" as const, text: agent.language, tone: "info" as const },
                      part(" ".repeat(Math.max(2, 16 - Bun.stringWidth(agent.language) - 2))),
                    ]
                  : [part(" ".repeat(16))]),
              ]
            : [part(" ")]),
          part(
            `${bar}  ${progress === undefined ? c`—` : `${Math.round(progress * 100)}%`}`,
            progress === undefined ? "muted" : statusTone(agent),
          ),
          ...(foldedFooter ? [part(` ${repeatCells(c`─`, innerWidth)}`, "muted")] : []),
        ],
        aside: [
          ...(foldedFooter
            ? [part(c`${count} · e expand all`, "muted")]
            : !narrow
              ? [part(c`${agent.files.length ? changed : "no changes"}  │  `, "muted"), ...actions]
              : [part(" o diff", "accent")]),
          part(foldedFooter ? c` ╯ ` : c` │ `, "muted"),
        ],
        rail: true,
        detail: { type: "column", children },
        underline: last,
      })
    }
  }
  const tree: UiNode = { type: "tree", id: "timeline", expanded: "all", items }
  const height = items.reduce(
    (sum, item) =>
      sum +
      1 +
      Number(!!item.underline) +
      (open(item.key) && item.detail && !Array.isArray(item.detail)
        ? item.detail.type === "column"
          ? item.detail.children.reduce((sum, child) => sum + Number(child.size ?? 1), 0)
          : 1
        : 0),
    0,
  )
  // Carry the rail through spare timeline space rather than inserting blank gap rows.
  return height >= ctx.height
    ? tree
    : {
        type: "column",
        children: [
          { size: height, node: tree },
          {
            node: text(
              Array.from({ length: ctx.height - height }, () =>
                segments([part(`${" ".repeat(compactLead ? 2 : 14)}${c`│`}`, "muted")]),
              ),
            ),
          },
        ],
      }
}

export function summary(source: DashboardSource, agent: DashboardAgent, ctx: UiContext): UiNode {
  const c = chrome(ctx)
  const detail = source.details(agent.id)
  const usage = detail?.stats?.usage
  const tokens = usage ? usage.input + usage.output : undefined
  const runtime =
    agent.durationMs ??
    (agent.startedAt !== undefined && ["working", "paused", "idle"].includes(displayState(agent))
      ? ctx.now - agent.startedAt
      : undefined)
  if (agent.durationMs === undefined && runtime !== undefined && displayState(agent) === "working")
    ctx.requestRefresh?.(1000)
  const stage = agent.card?.kind === "stage"
  if (stage) {
    const remaining = stageDetail(agent)
    const notes = [
      ...(detail?.notes ?? []),
      ...(source.snapshot().warning ? [{ kind: "warning" as const, text: source.snapshot().warning! }] : []),
    ]
    return text(
      [
        segments(stageHeading(agent, ctx)),
        ...(remaining ? [{ kind: "text" as const, text: remaining }] : []),
        ...(detail?.summary ?? []).filter((line) => {
          const value = line.kind === "segments" ? line.parts.map((part) => part.text).join("") : line.text
          return ![
            remaining,
            agent.task,
            agent.card?.label,
            agent.card?.outcome,
            agent.card?.costText,
          ].includes(value)
        }),
        ...(runtime === undefined
          ? []
          : [{ kind: "muted" as const, text: `Runtime  ${duration(runtime, ctx)}` }]),
        ...(agent.startedAt === undefined
          ? []
          : [{ kind: "muted" as const, text: `Started  ${clock(agent.startedAt)}` }]),
        ...(detail?.steps?.length
          ? detail.steps.map((step) => segments([...statusBadge(step, ctx), part(` ${step.text}`)]))
          : []),
        ...(agent.files.length
          ? [
              segments([part("Reported files", "accent")]),
              ...agent.files.map((file) => segments(fileParts(file, Math.max(1, ctx.width - 2), ctx))),
            ]
          : []),
        ...(notes.length ? [{ kind: "text" as const, text: "" }, ...notes] : []),
      ],
      "summary",
    )
  }
  const values = [
    ["Agent", rowLabel(agent)],
    ["Task", agent.task],
    ["Kind", agent.language ?? c`—`],
    ["Status", ""],
    ["Runtime", duration(runtime, ctx)],
    ["Started", clock(agent.startedAt)],
    [
      tokens === undefined ? "Cost" : "Tokens",
      `${tokens === undefined ? "" : `${(tokens / 1000).toFixed(1)}k${c` · `}`}${agent.cost === undefined ? "unknown" : formatCost(agent.cost)}`,
    ],
  ]
  const doing: ViewLine[] = [
    segments([part("What this agent is doing", "accent")]),
    ...(detail?.summary.length ? detail.summary : [{ kind: "text" as const, text: agent.task }]),
    ...(detail?.steps?.length
      ? [
          { kind: "text" as const, text: "" },
          segments([
            part(
              `Steps  ${detail.steps.filter((step) => step.status === "done").length}/${detail.steps.length}`,
              "muted",
            ),
          ]),
          ...detail.steps.map((step) => segments([...statusBadge(step, ctx), part(` ${step.text}`)])),
        ]
      : []),
  ]
  const notes = [
    ...(detail?.notes ?? []),
    ...(source.snapshot().warning ? [{ kind: "warning" as const, text: source.snapshot().warning! }] : []),
  ]
  const valueLine = ([key, value]: string[]): ViewLine =>
    segments(
      key === "Status"
        ? [part(key.padEnd(9)), ...statusBadge(agent, ctx)]
        : [part(`${key!.padEnd(9)}${value}`)],
    )
  if (ctx.width < 110)
    return text(
      [
        segments([
          part(c`${rowLabel(agent)} · `, "accent"),
          ...statusBadge(agent, ctx),
          part(c` · ${duration(runtime, ctx)}`, "accent"),
        ]),
        { kind: "text", text: agent.task },
        ...doing.slice(1),
        { kind: "text", text: "" },
        ...values.slice(2).map(valueLine),
        { kind: "text", text: "" },
        segments([part("Changed files", "accent")]),
        ...agent.files.map((file) => segments(fileParts(file, Math.max(1, ctx.width - 2), ctx))),
        ...(!agent.files.length ? [{ kind: "muted" as const, text: "No files reported." }] : []),
        ...(notes.length
          ? [{ kind: "text" as const, text: "" }, segments([part("Notes", "accent")]), ...notes]
          : []),
      ],
      "summary",
    )
  return {
    type: "row",
    divider: true,
    gap: 1,
    children: [
      {
        size: 33,
        node: text(values.map(valueLine), "summary"),
      },
      { node: text(doing, "summary-activity") },
      {
        size: "28%",
        node: text(
          [
            segments([part("Changed files", "accent"), part(`  ${agent.files.length} files`, "muted")]),
            ...agent.files.map((file) =>
              segments(fileParts(file, Math.max(1, Math.floor((ctx.width - 4) * 0.28) - 2), ctx)),
            ),
            ...(!agent.files.length ? [{ kind: "muted" as const, text: "No files reported." }] : []),
            ...(notes.length
              ? [{ kind: "text" as const, text: "" }, segments([part("Notes", "accent")]), ...notes]
              : []),
          ],
          "summary-files",
        ),
      },
    ],
  }
}
