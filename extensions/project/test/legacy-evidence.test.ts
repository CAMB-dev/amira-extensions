import { expect, test } from "bun:test"
import { createHash } from "node:crypto"
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import path from "node:path"
import type { CommandContext, ConversationSpec, ExtensionAPI } from "@amira/api"
import { disposeAccounting } from "../src/accounting.ts"
import { DesignSessions } from "../src/design.ts"
import { createProject, DecisionStore, readDocument } from "../src/store.ts"
import { ownedFixture } from "./owned-fixture.ts"

const hash = (text: string) => createHash("sha256").update(text).digest("hex")
test("legacy Other is not exposed as a human rationale, while original evidence/hash history is preserved", async () => {
  const root = await mkdtemp(path.join(tmpdir(), "project-legacy-evidence-"))
  let api: ExtensionAPI | undefined
  try {
    const project = await createProject(root, "Legacy")
    const question = {
      question: "Which store?",
      options: [
        { label: "Local", description: "Offline; manual backups" },
        { label: "Remote", description: "Sync; needs hosting" },
      ],
    }
    const answer = { selected: [], other: "SQLite instead" }
    const record = {
      id: "D1",
      question,
      answer,
      date: "2026-10-14T00:00:00.000Z",
      language: "en",
      sessionId: "legacy-design",
      askId: "legacy-ask",
      provenance: "human",
      rationale: "SQLite instead",
      supersedes: [],
      supersededBy: [],
    }
    // Exact original format-1 generated bytes, including its incorrect automatic rationale.
    const oldMarkdown = `## D1: Which store?\n\nDate: ${record.date}\nLanguage: en\n\n### Options and trade-offs\n- [ ] Local — Offline; manual backups\n- [ ] Remote — Sync; needs hosting\n\nHuman choice: Other\nOther (exact human text): SQLite instead\nRationale: SQLite instead\n\nEvidence (human response): session=legacy-design; ask=legacy-ask\n`
    const raw = `${JSON.stringify({ schemaVersion: 1, questions: [question], answers: [answer], meta: { sessionId: record.sessionId, askId: record.askId, language: "en", supersedes: [] }, records: [record], priorGeneratedHash: hash("") })}\n`
    const folder = path.join(root, ".amira", "project")
    await writeFile(path.join(folder, "decisions.evidence.jsonl"), raw)
    await writeFile(path.join(folder, "decisions.md"), oldMarkdown)
    await writeFile(
      path.join(folder, "decisions.manifest.json"),
      JSON.stringify({ schemaVersion: 1, hash: hash(oldMarkdown) }),
    )
    const store = new DecisionStore(project)
    expect((await store.records())[0]?.rationale).toBeUndefined()
    expect((await store.records())[0]?.answer.other).toBe("SQLite instead")
    expect((await store.recover()).conflict).toBe(false)
    expect(await readDocument(project, "decisions.md")).not.toContain("Rationale: SQLite instead")
    expect(await readDocument(project, "decisions.md")).toContain("Other (exact human text): SQLite instead")
    expect(await readFile(path.join(folder, "decisions.evidence.jsonl"), "utf8")).toBe(raw)

    let seed = ""
    const session = { info: () => ({ id: "main" }) }
    api = {
      dataDir: path.join(root, "host-data"),
      session: () => session,
      conversations: {
        openOrCreate: async (spec: ConversationSpec) => {
          seed = spec.systemPrompt
          return ownedFixture(spec, "owned")
        },
      },
    } as unknown as ExtensionAPI
    const ctx = {
      session,
      signal: new AbortController().signal,
      print() {},
      focusConversation: () => true,
      unfocusConversation: () => true,
    } as unknown as CommandContext
    await new DesignSessions(api).open(project, ctx, "en")
    const verified = JSON.parse(seed.split("VERIFIED_DECISION_RECORDS: ")[1]!.split("\n")[0]!)
    expect(verified[0].rationale).toBeUndefined()
    expect(verified[0].answer.other).toBe("SQLite instead")
    await store.record([question], [{ selected: ["Remote"] }], {
      sessionId: "new-design",
      askId: "new-answer",
      language: "en",
      supersedes: ["D1"],
    })
    expect((await store.records()).map((entry) => entry.id)).toEqual(["D1", "D2"])
    expect((await store.recover()).conflict).toBe(false)
    expect((await readFile(path.join(folder, "decisions.evidence.jsonl"), "utf8")).startsWith(raw)).toBe(true)
    expect(await readDocument(project, "decisions.md")).not.toContain("Rationale: SQLite instead")
  } finally {
    if (api) await disposeAccounting(api)
    await rm(root, { recursive: true, force: true })
  }
})
